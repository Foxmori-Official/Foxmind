let activeLocale = /^zh(?:[-_]|$)/i.test(chrome.i18n.getUILanguage()) ? 'zh' : 'en'
export async function initializeLocale() {
  const { uiLocale } = await getSettings()
  activeLocale = uiLocale === 'auto' ? (/^zh(?:[-_]|$)/i.test(chrome.i18n.getUILanguage()) ? 'zh' : 'en')
    : uiLocale === 'zh-CN' ? 'zh' : 'en'
  localize()
}
export const uiLanguage = () => activeLocale
export const t = (key: string) => {
  const copy = uiLanguage() === 'zh' ? zh : en
  return Object.hasOwn(copy, key) ? copy[key as keyof typeof copy] : copy.genericError
}

export function localize() {
  document.documentElement.lang = uiLanguage()
  for (const item of document.querySelectorAll<HTMLElement>('[data-msg]')) {
    item.textContent = t(item.dataset.msg ?? '')
  }
  for (const item of document.querySelectorAll<HTMLElement>('[data-msg-aria]')) {
    item.setAttribute('aria-label', t(item.dataset.msgAria ?? ''))
  }
}

export function el<T extends HTMLElement>(id: string): T {
  return document.getElementById(id) as T
}

export function errorCopy(error: unknown, fallback = 'genericError'): string {
  return t(error instanceof FoxmindError ? error.code : fallback)
}
